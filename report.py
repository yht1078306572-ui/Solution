def build_docx(cfg, top_png, side_png, out_path):
    doc = Document()
    for s in doc.sections:
        s.top_margin, s.bottom_margin = Cm(2.5), Cm(2.5)
        s.left_margin, s.right_margin = Cm(2.8), Cm(2.8)

    # 页眉：青瞳 logo（封面所在首页不显示页眉）
    logo_path = os.path.join(ASSETS, "logo.png")
    for s in doc.sections:
        s.different_first_page_header_footer = True
        if os.path.exists(logo_path):
            hp = s.header.paragraphs[0]
            hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            hp.add_run().add_picture(logo_path, width=Cm(3.2))

    rw = RW(doc, cfg, out_path)
    rw.top_png = top_png
    rw.side_png = side_png

    make_cover(rw)
    for ch in compose_chapters(cfg["scene"], cfg.get("detail", "standard")):
        CHAPTERS[ch](rw)
    if cfg.get("detail", "standard") != "basic":
        insert_toc(rw)
    enable_update_fields(doc)

    doc.save(out_path)
    return out_path
