def compose_chapters(scene_key, detail):
    """按详略程度组合章节流：basic=基础版 / standard=标准版 / full=深度版"""
    base = list(FLOWS.get(scene_key, FLOWS["robot"]))
    if detail == "basic":
        return base
    ch = []
    for i, c in enumerate(base):
        if c == "company":
            ch.append("training")
        ch.append(c)
        if i == 0 and detail == "full":
            ch.append("industry")
        if c == "scheme":
            ch.append("product")
            if detail == "full":
                ch.append("tech_key")
            ch.append("operation")
            if detail == "full":
                ch += ["software_detail", "sop", "data_mgmt"]
        elif c == "accessories" and detail == "full" and "custom_reliability" not in base:
            ch.append("custom_reliability")
        elif c == "bom":
            ch.append("delivery")
        elif c == "env" and detail == "full" and "acceptance" not in base \
                and "joint_test" not in base:
            ch.append("acceptance_general")
    if detail == "full":
        ch.append("faq")
        ch.append("appendix")
    return ch

