# ---------------------------------------------------------------- 基础排版
def _font(run, size=11, bold=False, color=DARK, name="宋体"):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), name)


class RW:
    """报告写作器：自动管理章节编号（一、/ X.Y）"""

    def __init__(self, doc, cfg, out_path):
        self.doc = doc
        self.cfg = cfg
        self.scene = SCENES[cfg["scene"]]
        self.chapter = 0
        self.section = 0
        self.toc = []
        self._toc_anchor = None
        self._out_dir = os.path.dirname(out_path)
        self._base = os.path.splitext(os.path.basename(out_path))[0]
        self._used_imgs = set()   # 全文图片去重（按文件名）

    def gen(self, fn, tag):
        path = os.path.join(self._out_dir, f"{self._base}_{tag}.png")
        if not os.path.exists(path):
            fn(path)
        return path

    def h1(self, title):
        self.chapter += 1
        self.section = 0
        text = f"{cn_num(self.chapter)}、{title}"
        self.toc.append((1, text))
        para = self.doc.add_paragraph(style="Heading 1")   # 大纲级别 1，供引用目录识别
        para.paragraph_format.space_before = Pt(0)
        para.paragraph_format.space_after = Pt(0)
        para.paragraph_format.line_spacing = 1.5
        run = para.add_run(text)
        _font(run, size=14, bold=True, color=DARK, name="宋体")   # 四号宋体加粗

    def h2(self, title):
        self.section += 1
        text = f"{self.chapter}.{self.section} {title}"
        self.toc.append((2, text))
        para = self.doc.add_paragraph(style="Heading 2")   # 大纲级别 2，供引用目录识别
        para.paragraph_format.space_before = Pt(0)
        para.paragraph_format.space_after = Pt(0)
        para.paragraph_format.line_spacing = 1.5
        run = para.add_run(text)
        _font(run, size=12, bold=True, color=DARK, name="宋体")   # 小四宋体加粗

    def p(self, text="", size=12, bold=False, align=None, color=DARK,
          space_after=0, name="宋体"):
        para = self.doc.add_paragraph()
        if align is not None:
            para.alignment = align
        para.paragraph_format.space_before = Pt(0)
        para.paragraph_format.space_after = Pt(space_after)
        para.paragraph_format.line_spacing = 1.5
        if text and align is None:
            para.paragraph_format.first_line_indent = Pt(size * 2)  # 首行缩进2字符
        run = para.add_run(text)
        _font(run, size=size, bold=bold, color=color, name=name)
        return para

    def bullets(self, items, numbered=False):
        for i, it in enumerate(items, 1):
            prefix = f"{i}. " if numbered else "• "
            para = self.doc.add_paragraph()
            para.paragraph_format.left_indent = Cm(0.6)
            para.paragraph_format.space_before = Pt(0)
            para.paragraph_format.space_after = Pt(2)
            para.paragraph_format.line_spacing = 1.5
            run = para.add_run(prefix + it)
            _font(run, size=12)

    def img(self, filename, width_cm=14.5, caption=None):
        path = filename if os.path.isabs(filename) else os.path.join(ASSETS, filename)
        if not os.path.exists(path):
            return
        key = os.path.basename(path).lower()
        if key in self._used_imgs:      # 同一图片全文只出现一次
            return
        self._used_imgs.add(key)
        para = self.doc.add_paragraph()
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        para.add_run().add_picture(path, width=Cm(width_cm))
        if caption:
            self.p(caption, size=9, align=WD_ALIGN_PARAGRAPH.CENTER,
                   color=LGRAY, space_after=10)

    def table(self, rows, header=True, widths=None):
        t = self.doc.add_table(rows=0, cols=len(rows[0]))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for ri, row in enumerate(rows):
            cells = t.add_row().cells
            for ci, val in enumerate(row):
                cells[ci].text = ""
                para = cells[ci].paragraphs[0]
                run = para.add_run(str(val))
                _font(run, size=10.5, bold=(header and ri == 0))
                if widths:
                    cells[ci].width = Cm(widths[ci])
        return t


