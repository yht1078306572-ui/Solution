def cn_num(n):
    """阿拉伯数字 → 中文章节数（支持 1-30）"""
    d = "一二三四五六七八九"
    if n <= 9:
        return d[n - 1]
    if n == 10:
        return "十"
    if n < 20:
        return "十" + d[n - 11]
    if n == 20:
        return "二十"
    return "二十" + d[n - 21]

