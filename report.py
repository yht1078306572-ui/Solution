def _add_toc_field(para):
    """在段落内写入 Word TOC 域（引用目录），打开文档时自动更新"""
    r1 = para.add_run()
    fld = OxmlElement("w:fldChar")
    fld.set(qn("w:fldCharType"), "begin")
    r1._r.append(fld)
    r2 = para.add_run()
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = ' TOC \\o "1-2" \\h \\z \\u '
    r2._r.append(instr)
    r3 = para.add_run()
    sep = OxmlElement("w:fldChar")
    sep.set(qn("w:fldCharType"), "separate")
    r3._r.append(sep)
    r4 = para.add_run("（目录为引用目录：打开文档时自动更新，或全选后按 F9 / 右键“更新域”刷新）")
    _font(r4, size=10.5, color=GRAY, name="宋体")
    r5 = para.add_run()
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    r5._r.append(end)


def insert_toc(rw):
    """在封面之后插入引用目录页（Word TOC 域，识别一/二级标题）"""
    if rw._toc_anchor is None:
        return
    anchor_para = rw.doc.paragraphs[rw._toc_anchor]
    title_p = anchor_para.insert_paragraph_before("")
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = title_p.add_run("目  录")
    _font(r, size=14, bold=True, color=DARK, name="宋体")
    toc_p = anchor_para.insert_paragraph_before("")
    _add_toc_field(toc_p)
    # 目录页结束分页
    from docx.enum.text import WD_BREAK
    br = anchor_para.insert_paragraph_before("")
    br.add_run().add_break(WD_BREAK.PAGE)


def enable_update_fields(doc):
    """设置打开文档时自动更新域（引用目录无需手动刷新）"""
    settings = doc.settings.element
    upd = settings.find(qn("w:updateFields"))
    if upd is None:
        upd = OxmlElement("w:updateFields")
        settings.append(upd)
    upd.set(qn("w:val"), "true")


