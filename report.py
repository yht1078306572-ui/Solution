    active = cfg["opts"].get("active_marker", True)
    dist = cam["dist_a"] if active else cam["dist_p"]
    fov_h, fov_v = cam["fov"]
    cov_h = 2 * dist * math.tan(math.radians(fov_h / 2))
    cov_v = 2 * dist * math.tan(math.radians(fov_v / 2))

    rw.h1("工程部署论证")
